/**
 * 1. Інтерфейс для будь-якого об'єкта, що зберігається в каталозі бібліотеки.
 * Визначає базовий "контракт" поведінки.
 */
public interface LibraryItem {

    /**
     * Повертає назву елемента.
     * @return String назва
     */
    String getTitle();

    /**
     * Повертає унікальний каталожний ID (наприклад, ISBN або інвентарний номер).
     * @return String каталожний ID
     */
    String getCatalogId();

    /**
     * Повертає кількість доступних екземплярів.
     * @return int кількість
     */
    int getAvailableCopies();

    /**
     * Визначає, чи можна видавати цей елемент на абонемент (додому).
     * @return true, якщо можна видавати, false (тільки для читального залу)
     */
    boolean isLoanable();

    /**
     * (Старий метод) Виводить деталі прямо в консоль.
     */
    void displayDetails();

    /**
     * (Новий метод) Повертає деталі у вигляді рядка для GUI.
     * @return String відформатована інформація про елемент
     */
    String getDetailsAsString();
}